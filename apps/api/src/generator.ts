export type Section = {
  type: string; label: string; eyebrow?: string; heading?: string; body?: string;
  image?: string; button?: string; link?: string; layout?: string;
};
export type PageDocument = { version: number; sections: Section[] };

const escapeHtml = (value = '') => value.replace(/[&<>"']/g, char => ({
  '&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'
}[char]!));

export function generateAstroProject(site: { name: string; description: string }, page: PageDocument) {
  const sections = page.sections.map((section, index) => {
    const image = section.image ? '<img class="section-image" src={'+JSON.stringify(section.image)+'} alt="" loading="lazy" />' : '';
    const button = section.button ? '<a class="button" href={'+JSON.stringify(section.link || '#')+'}>{'+JSON.stringify(section.button)+'}</a>' : '';
    return `<section class="section ${escapeHtml(section.layout || 'standard')}" id="section-${index + 1}">
  ${section.eyebrow ? `<p class="eyebrow">${escapeHtml(section.eyebrow)}</p>` : ''}
  <h2>${escapeHtml(section.heading || section.label)}</h2>
  <p>${escapeHtml(section.body || '')}</p>
  ${image}
  ${button}
</section>`;
  }).join('\n');
  const pageSource = `---
const siteName = ${JSON.stringify(site.name)};
---
<!doctype html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <meta name="description" content={${JSON.stringify(site.description)}} />
  <title>{siteName}</title>
  <style>
    :root{font-family:Inter,system-ui,sans-serif;color:#24342a;background:#fff}*{box-sizing:border-box}body{margin:0}header{padding:24px 7%;border-bottom:1px solid #edf0eb}main{max-width:1080px;margin:auto;padding:8vh 28px}h1{font-size:clamp(38px,6vw,68px);line-height:1.05;letter-spacing:-.04em}h2{font-size:clamp(26px,4vw,42px);letter-spacing:-.03em}.intro{color:#68756c;font-size:18px;line-height:1.7}.section{padding:52px 0;border-top:1px solid #edf0eb}.section p{color:#68756c;line-height:1.8;max-width:720px}.section-image{max-width:100%;max-height:460px;object-fit:cover;border-radius:18px;margin-top:18px}.button{display:inline-block;background:#20372c;color:#fff;text-decoration:none;padding:13px 20px;border-radius:8px;margin-top:12px}.eyebrow{text-transform:uppercase;letter-spacing:.14em;font-size:11px}
  </style>
</head>
<body>
  <header><strong>{siteName}</strong></header>
  <main>
    <p class="eyebrow">Welcome</p>
    <h1>{siteName}</h1>
    <p class="intro">${escapeHtml(site.description)}</p>
    ${sections}
  </main>
</body>
</html>`;
  return {
    'package.json': JSON.stringify({ name: site.name.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,''), type:'module', scripts:{dev:'astro dev',build:'astro build',preview:'astro preview'}, dependencies:{astro:'^5.13.0'} }, null, 2),
    'astro.config.mjs': "import { defineConfig } from 'astro/config';\nexport default defineConfig({});\n",
    'src/pages/index.astro': pageSource,
    'README.md': `# ${site.name}\n\nGenerated by Astroid.\n\n${site.description}\n\nRun with \`npm install && npm run dev\`.\n\nDeploy with GitHub Actions after enabling GitHub Pages for this repository.\n`,
    '.github/workflows/deploy.yml': `name: Deploy Astro site\non:\n  push:\n    branches: [main]\n  workflow_dispatch:\npermissions:\n  contents: read\n  pages: write\n  id-token: write\nconcurrency:\n  group: pages\n  cancel-in-progress: true\njobs:\n  build:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/checkout@v4\n      - uses: actions/setup-node@v4\n        with:\n          node-version: 20\n          cache: npm\n      - run: npm install\n      - run: npm run build\n      - uses: actions/upload-pages-artifact@v3\n        with:\n          path: ./dist\n  deploy:\n    environment:\n      name: github-pages\n      url: \${{ steps.deployment.outputs.page_url }}\n    runs-on: ubuntu-latest\n    needs: build\n    steps:\n      - id: deployment\n        uses: actions/deploy-pages@v4\n`
  };
}